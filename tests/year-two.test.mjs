import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const load=(path,expr)=>{const cx=vm.createContext({});vm.runInContext(read(path),cx,{filename:path});return JSON.parse(vm.runInContext('JSON.stringify('+expr+')',cx))};
const book=load('data/campaign.js','BOOK');
const dispatch=load('home/dispatches.js','HOUSE_DISPATCHES');
const summary=load('annual/summaries.js','ANNUAL_SUMMARIES');
const base=JSON.parse(read('data/save-baseline.json'));
const projection=JSON.parse(read('data/approved-save-projection.json'));
test('La campaña, los resúmenes y la Gaceta avanzan con el guardado aprobado',()=>{
 assert.equal(book.meta.year,2);
 assert.equal(book.meta.day,base.lastApprovedVisibleDay);
 assert.equal(book.stats.gold,projection.guild.gold);
 assert.equal(book.stats.renown,projection.guild.renown);
 assert.equal(book.stats.members,projection.guild.roster.length);
 assert.equal(book.stats.dead,projection.guild.fallen.length);
 assert.equal(book.stats.delves,projection.guild.tally.delves);
 assert.equal(book.stats.salaryCycle,projection.guild.roster.reduce((sum,x)=>sum+(x.oathWage||0),0));
 assert.equal(book.stats.bonds,Object.keys(projection.guild.bonds).length);
 assert.equal(book.world.division,'Frontera');
 assert.equal(dispatch.latestDay,book.meta.day);
 assert.equal(dispatch.latestEdition,book.editions.at(-1).id);
 assert.equal(summary.years[0].year,1);
 assert.equal(summary.years[0].title,'El año que hicimos casa');
});
test('La Casa conserva a los caídos, vendidos y retirados sin meterlos en la plantilla',()=>{
 const live=book.characters.filter(x=>!['caído','retirada','vendida'].includes(x.status));
 assert.equal(live.length,book.stats.members);
 assert.equal(book.characters.find(x=>x.name==='Brugo').status,'caído');
 assert.equal(book.characters.find(x=>x.name==='Turca de la Tormenta').status,'retirada');
 const xara=book.characters.find(x=>x.name==='Xara del Cuerno');
 assert.equal(xara.status,'vendida');
 assert.equal(xara.departure.fee,1240);
 assert.equal(xara.departure.buyer,'El Cónclave de Azulhondo');
 const roc=book.characters.find(x=>x.name==='Roc Guardalmena');
 assert.ok(roc.recruited&&roc.status==='en camino');
 assert.equal(roc.currentAbility,98);
 assert.equal(roc.potentialAbility,128);
 assert.equal(roc.away.returnsDay,165);
 assert.equal(roc.portrait,'Roc Guardalmena');
 assert.notEqual(roc.portrait,'Xara del Cuerno');
 assert.ok(!live.includes(xara));
 assert.ok(live.includes(roc));
});
test('Los regresos y nuevas crónicas no inventan resultados',()=>{
 const exp=book.world.activeExpedition;
 assert.equal(exp.outcome,'pendiente');
 assert.equal(exp.heroIds.length,4);
 assert.ok(book.world.activeJobs.some(x=>x.heroIds.includes('adv_xhgcncku9qpi')));
 assert.ok(book.world.activeJobs.some(x=>x.heroIds.includes('adv_dw6dpd5sh7jc')));
 const html=read('index.html');
 for(const slug of ['interludio-xxiv-el-sitio-que-no-se-vende','interludio-xxv-la-firma-y-el-camino']){
  assert.ok(html.includes(slug+'.js'),'Falta crónica '+slug);
  const ctx=vm.createContext({});
  vm.runInContext('var BOOK={chapters:[]}',ctx);
  vm.runInContext(read('novel/chapters/'+slug+'.js'),ctx);
  const chapter=JSON.parse(vm.runInContext('JSON.stringify(BOOK.chapters[0])',ctx));
  assert.ok(chapter.paragraphs.length>20);
  for(const idx of Object.keys(chapter.speakers||{}))assert.ok(chapter.paragraphs[Number(idx)].startsWith('—'),'Error en atribución de diálogo '+slug+' #'+idx);
 }
});
test('La economía separa nómina real y estimación siguiente',()=>{
 const f=book.world.finance,c=f.current,p=f.lastPayroll;
 assert.equal(c.stipend-c.delverWages-c.staffWages-c.upkeep,c.netBeforeDelves);
 assert.equal(f.netWithAvgDelves,c.netBeforeDelves+f.avgDelvesGoldPerPay);
 assert.equal(f.asOfVisibleDay,book.meta.day);
 assert.equal(p.net,projection.guild.financeSnapshot.lastPaydayNet);
});
